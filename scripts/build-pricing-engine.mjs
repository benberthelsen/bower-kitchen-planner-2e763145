/**
 * Bundle the real pricing engine for the `price-quote` edge function.
 *
 *   npm run build:pricing-engine
 *
 * Produces supabase/functions/price-quote/engine.mjs from src/lib/pricing —
 * the SAME source the planner UI runs. This is a build step, not a fork: edit
 * the TypeScript, rebuild, redeploy. Deno cannot resolve the `@/` alias or
 * bare .ts imports across the project, hence the bundle.
 *
 * The only non-pure module in the tree is fetchAllPricingRows.ts (browser
 * Supabase client). quoteFromSchedule does not import it, but it is marked
 * external anyway so a future import cannot drag the browser client into Deno.
 */
import { build } from 'esbuild';
import { statSync } from 'node:fs';

const outfile = 'supabase/functions/price-quote/engine.mjs';

await build({
  entryPoints: ['src/lib/pricing/quoteFromSchedule.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile,
  alias: { '@': './src' },
  external: ['@/integrations/supabase/client'],
  banner: { js: '// GENERATED by scripts/build-pricing-engine.mjs — do not edit; edit src/lib/pricing and rebuild.' },
  logLevel: 'warning',
});

const kb = Math.round(statSync(outfile).size / 1024);
console.log(`pricing engine bundled -> ${outfile} (${kb} KB)`);
